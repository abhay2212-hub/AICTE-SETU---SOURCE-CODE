"""Write the `credentials` test vectors in shared/test-vectors.json (shared/credentials.md).

Signed with the fixed TEST seed in app.services.credentials, never the production key.
Deterministic: running it again writes the same vectors. Run from backend/:

    uv run python -m scripts.credential_vectors
"""

from __future__ import annotations

import base64
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from app.services import credentials as cred

VECTORS = Path(__file__).resolve().parents[2] / "shared" / "test-vectors.json"
STUDENT_ID = "40000000-0000-4000-8000-000000000001"
ISSUED_AT = datetime(2026, 9, 10, 8, 0, tzinfo=UTC)
CLAIMS = {
    "academic_year": "2026-27",
    "enrolment_status": "student_confirmed",
    "institution": "Meghdoot Institute of Engineering",
    "programme": "B.Tech Computer Science and Engineering",
}


def _payload(credential_id: str, audience: str, expiry: str, nonce: str) -> dict[str, Any]:
    return cred.build_payload(
        student_id=STUDENT_ID,
        audience=audience,
        claims=CLAIMS,
        expiry=expiry,
        pseudonym_secret=cred.TEST_PSEUDONYM_SECRET,
        now=ISSUED_AT,
        credential_id=credential_id,
        nonce=nonce,
    )


def _tamper(qr_text: str) -> str:
    envelope = json.loads(base64.urlsafe_b64decode(qr_text + "=" * (-len(qr_text) % 4)))
    envelope["payload"]["claims"]["enrolment_status"] = "submitted"
    raw = json.dumps(envelope, separators=(",", ":"), ensure_ascii=False).encode()
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def build() -> dict[str, Any]:
    key = cred.signing_key(cred.TEST_SEED_HEX)
    valid = _payload("92000000-0000-4000-8000-000000000001", "Acme Infotech", "7d", "0" * 31 + "1")
    expired = _payload(
        "92000000-0000-4000-8000-000000000002", "Acme Infotech", "15m", "0" * 31 + "2"
    )
    revoked = _payload(
        "92000000-0000-4000-8000-000000000003", "Merit Scholarship Cell", "1d", "0" * 31 + "3"
    )
    valid_qr = cred.sign(valid, key)
    check_at = valid["iat"] + 3600

    def case(name: str, payload: dict, qr: str, expect: dict, revoked_ids=()) -> dict:
        return {
            "name": name,
            "qr_text": qr,
            "payload": payload,
            "canonical_payload": cred.canonical_bytes(payload).decode("utf-8"),
            "verify_at": check_at,
            "revoked_ids": list(revoked_ids),
            "expect": expect,
        }

    return {
        "note": (
            "Signed with the fixed TEST seed below, which is not the production"
            " CREDENTIAL_SIGNING_KEY. Generated by backend/scripts/credential_vectors.py."
            " verify_at is the Unix time to check against."
        ),
        "test_seed_hex": cred.TEST_SEED_HEX,
        "public_key_b64": cred.public_key_b64(key),
        "key_id": cred.key_id(key),
        "pseudonym_secret": cred.TEST_PSEUDONYM_SECRET,
        "student_id": STUDENT_ID,
        "cases": [
            case(
                "valid",
                valid,
                valid_qr,
                {"valid": True, "claims": CLAIMS, "expires_at": valid["exp"]},
            ),
            case(
                "tampered",
                {**valid, "claims": {**CLAIMS, "enrolment_status": "submitted"}},
                _tamper(valid_qr),
                {"valid": False, "reason": "bad_signature"},
            ),
            case(
                "expired",
                expired,
                cred.sign(expired, key),
                {"valid": False, "reason": "expired", "expires_at": expired["exp"]},
            ),
            case(
                "revoked",
                revoked,
                cred.sign(revoked, key),
                {"valid": False, "reason": "revoked", "expires_at": revoked["exp"]},
                revoked_ids=[revoked["id"]],
            ),
        ],
    }


def main() -> None:
    vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
    vectors["_note"] = "Dev A fills blind_match; Dev B fills credentials"
    vectors["credentials"] = build()
    text = json.dumps(vectors, indent=2, ensure_ascii=False) + "\n"
    VECTORS.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(vectors['credentials']['cases'])} credential vectors to {VECTORS}")


if __name__ == "__main__":
    main()
